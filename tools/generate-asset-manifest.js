const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const assetFiles = require('../asset-files.json');
const versionText = fs.readFileSync(path.join(root, 'version.js'), 'utf8');
const version = versionText.match(/self\.APP_VERSION\s*=\s*['"]([^'"]+)['"]/)?.[1];
const htmlVersion = fs.readFileSync(path.join(root, 'index.html'), 'utf8')
  .match(/<meta name="app-release" content="([^"]+)"\s*\/?\s*>/)?.[1];
if (!version || version !== htmlVersion || new Set(assetFiles).size !== assetFiles.length) {
  throw new Error('App versions must match in version.js and index.html, and offline asset paths must be unique.');
}
const hashes = Object.fromEntries(assetFiles.map((asset) => {
  if (!/^\.\/(?!.*\.\.)[A-Za-z0-9_./-]+$/.test(asset)) throw new Error(`Invalid asset path: ${asset}`);
  const content = fs.readFileSync(path.join(root, asset));
  if (/\.(?:js|html|css|json)$/.test(asset) && !asset.startsWith('./data/c56x/') &&
      content.includes(Buffer.from('\r\n'))) {
    throw new Error(`${asset} must use LF line endings for reproducible release hashes.`);
  }
  return [asset, crypto.createHash('sha256').update(content).digest('hex')];
}));
const digest = crypto.createHash('sha256')
  .update(JSON.stringify({ version, hashes })).digest('hex');
const manifest = { version, buildId: digest, hashes };
const output = `// Generated by tools/generate-asset-manifest.js; do not edit manually.\n` +
  `self.EFB_ASSET_MANIFEST = ${JSON.stringify(manifest, null, 2)};\n`;
const outputPath = path.join(root, 'asset-manifest.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== output) {
    console.error('Offline asset manifest is stale. Run npm run assets:generate and review the changes.');
    process.exitCode = 1;
  } else {
    console.log(`Offline asset manifest matches ${assetFiles.length} files (${digest.slice(0, 12)}).`);
  }
} else {
  fs.writeFileSync(outputPath, output);
  console.log(`Generated offline asset manifest for ${assetFiles.length} files (${digest.slice(0, 12)}).`);
}
